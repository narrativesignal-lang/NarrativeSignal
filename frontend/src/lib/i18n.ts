function getStoredLocale(): Locale {
  if (typeof window === "undefined") return "en";
  const stored = localStorage.getItem(STORAGE_KEY);
  if (stored === "zh" || stored === "es" || stored === "pt") return stored;
  return "en";
}

/** Stable copy for auth errors (avoids returning bare i18n keys if `t` runs before locale hydrates). */
export function getRateLimitMessage(locale: Locale): string {
  return (
    translations[locale]?.["auth.rateLimit"] ??
    translations.en["auth.rateLimit"] ??
    "Too many requests. Please wait a few seconds and try again."
  );
}

const I18nContext = createContext<{
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: (key: string, params?: Record<string, string | number>) => string;
}>({
  locale: "en",
  setLocale: () => {},
  t: (k) => k,
});

function interpolate(str: string, params?: Record<string, string | number>): string {
  if (!params) return str;
  return Object.entries(params).reduce((s, [k, v]) => s.replace(new RegExp(`\\{${k}\\}`, "g"), String(v)), str);
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("en");

  useLayoutEffect(() => {
    setLocaleState(getStoredLocale());
  }, []);

  useEffect(() => {
    if (typeof document !== "undefined")
      document.documentElement.lang =
        locale === "zh" ? "zh-CN" : locale === "es" ? "es" : locale === "pt" ? "pt" : "en";
  }, [locale]);

  const setLocale = useCallback((l: Locale) => {
    setLocaleState(l);
    if (typeof window !== "undefined") localStorage.setItem(STORAGE_KEY, l);
  }, []);

  const t = useCallback(
    (key: string, params?: Record<string, string | number>): string => {
      const map = translations[locale];
      const overlay = i18nOverlay[locale];
      const raw =
        map?.[key] ??
        overlay?.[key] ??
        translations.en[key] ??
        i18nOverlay.en[key] ??
        key;
      return interpolate(raw, params);
    },
    [locale]
  );

  return React.createElement(I18nContext.Provider, { value: { locale, setLocale, t } }, children);
}

export function useI18n() {
  return useContext(I18nContext);
}
